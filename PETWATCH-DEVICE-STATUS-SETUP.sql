-- PetWatch device heartbeat table.
-- Run this in Supabase Dashboard > SQL Editor.
-- Keep RLS enabled. This policy lets signed-in dashboard users read device status.
-- Do not add an unrestricted anon INSERT/UPDATE policy for the ESP32.

create table if not exists public.device_status (
  id bigint generated by default as identity primary key,
  device_name text not null unique,
  is_online boolean not null default false,
  last_seen timestamptz,
  updated_at timestamptz not null default now()
);

alter table public.device_status enable row level security;

drop policy if exists "Authenticated users can read PetWatch device status" on public.device_status;
create policy "Authenticated users can read PetWatch device status"
  on public.device_status
  for select
  to authenticated
  using (true);

-- Seed the expected device row. The ESP32/secure server-side heartbeat should
-- update this same row on every successful connection/heartbeat.
insert into public.device_status (device_name, is_online, last_seen)
select 'PetWatch', false, null
where not exists (
  select 1 from public.device_status where device_name = 'PetWatch'
);
